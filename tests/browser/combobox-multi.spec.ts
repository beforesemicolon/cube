test('allow-custom opt-in commits trimmed unmatched text once, preserves options and participates in forms', async ({ page }) => {
    await mount(page)
    const combo = page.locator('cb-combobox'), input = combo.getByRole('combobox')
    await page.locator('form').evaluate(form => { form.addEventListener('submit', event => event.preventDefault()) })
    await expect(combo).toHaveJSProperty('allowCustom', false)
    await input.fill('Sample font')
    await input.press('Enter')
    await expect(combo).toHaveJSProperty('value', ['at'])
    await expect(input).toHaveValue('Sample font')
    await combo.evaluate(node => node.setAttribute('allow-custom', ''))
    await expect(combo).toHaveAttribute('allow-custom', '')
    await input.fill('  Sample font  ')
    await input.press('Space')
    await expect(combo).toHaveJSProperty('value', ['at'])
    await input.press('Enter')
    await expect(combo).toHaveJSProperty('value', ['at', 'Sample font'])
    await expect(combo.getByRole('button', { name: 'Remove Sample font', exact: true })).toBeVisible()
    await expect(input).toHaveValue('')
    await expect(input).toHaveAttribute('aria-expanded', 'true')
    await expect.poll(() => combo.evaluate(node => (node as Combobox).options.length)).toBe(7)
    const values = await page.locator('form').evaluate(form => {
        if (!(form instanceof HTMLFormElement)) throw new Error('Missing form')
        return new FormData(form).getAll('country')
    })
    expect(values).toEqual(['at', 'Sample font'])
    await input.fill(' Sample font ')
    await input.press('Enter')
    await expect(input).toHaveValue('')
    await expect(combo).toHaveJSProperty('value', ['at', 'Sample font'])
    await input.fill('   ')
    await input.press('Enter')
    await expect(combo).toHaveJSProperty('value', ['at', 'Sample font'])
    await expect(combo).toHaveAttribute('data-changes', JSON.stringify([{ value: ['at', 'Sample font'], previousValue: ['at'] }] satisfies ValueChange[]))
    await combo.evaluate(node => node.setAttribute('allow-custom', 'false'))
    await input.fill('Blocked font')
    await input.press('Enter')
    await expect(combo).toHaveJSProperty('value', ['at', 'Sample font'])
    await page.locator('form').evaluate(form => { if (form instanceof HTMLFormElement) form.reset() })
    await expect(combo).toHaveJSProperty('value', ['at'])
    await expect(input).toHaveValue('')
})

