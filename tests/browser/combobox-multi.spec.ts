for (const key of ['Enter', 'Space']) test(`sole match is highlighted and ${key} accepts it without moving input focus`, async ({ page }) => {
    await mount(page)
    const combo = page.locator('cb-combobox'), input = combo.getByRole('combobox')
    await page.locator('form').evaluate(form => {
        form.dataset.submits = '0'
        form.addEventListener('submit', event => { event.preventDefault(); form.dataset.submits = String(Number(form.dataset.submits) + 1) })
    })
    await input.fill('Czech')
    const option = combo.getByRole('option', { name: 'Czech Republic', exact: true })
    await expect(option).toHaveAttribute('data-highlighted', 'true')
    await expect(option).toHaveAttribute('aria-selected', 'false')
    await expect(input).toHaveAttribute('aria-activedescendant', await option.getAttribute('id') ?? '')
    await expect(input).toBeFocused()
    expect((await new AxeBuilder({ page }).include('#fixture').analyze()).violations).toEqual([])
    await input.press(key)
    await expect(combo).toHaveJSProperty('value', ['at', 'cz'])
    await expect(input).toHaveValue('')
    await expect(input).toBeFocused()
    await expect(input).toHaveAttribute('aria-expanded', 'true')
    await expect(input).not.toHaveAttribute('aria-activedescendant')
    await expect(page.locator('form')).toHaveAttribute('data-submits', '0')
    await expect(combo).toHaveAttribute('data-changes', JSON.stringify([{ value: ['at', 'cz'], previousValue: ['at'] }] satisfies ValueChange[]))
    // Accepting the same label again must not toggle off an existing chip.
    await input.fill('Czech')
    await input.press(key)
    await expect(combo).toHaveJSProperty('value', ['at', 'cz'])
    await expect(input).toHaveValue('')
    await expect(combo).toHaveAttribute('data-changes', JSON.stringify([{ value: ['at', 'cz'], previousValue: ['at'] }] satisfies ValueChange[]))
    await expect(combo).toHaveAttribute('data-actions', '0')
})

