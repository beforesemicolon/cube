import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import type { Combobox } from '../../components/form/combobox/index.js'

type Value = string | string[]
interface ValueChange { value: Value; previousValue: Value }

async function mount(page: Page, appearance = 'light'): Promise<void> {
    await page.goto('/tests/browser/fixture.html')
    await page.waitForFunction(() => Boolean(customElements.get('cb-combobox')))
    await page.locator('#theme').evaluate((node, mode) => node.setAttribute('appearance', mode), appearance)
    await page.evaluate(() => {
        const form = document.createElement('form'), combo = document.createElement('cb-combobox')
        Object.assign(combo, {
            multi: true, value: ['at'], name: 'country', accessibleLabel: 'Countries',
            toggleLabel: 'Toggle countries', removeLabel: 'Remove {label}', placeholder: 'Choose a country', emptyLabel: 'No matching countries',
            options: [{ value: 'at', label: 'Austria' }, { value: 'by', label: 'Belarus', disabled: true }, { value: 'be', label: 'Belgium' }, { value: 'bg', label: 'Bulgaria' }, { value: 'cy', label: 'Cyprus' }, { value: 'cz', label: 'Czech Republic' }, { value: 'comma,value', label: 'Value, with comma' }],
        } satisfies Partial<Combobox>)
        combo.style.cssText = 'width:280px;max-width:100%'
        const changes: ValueChange[] = []
        combo.dataset.changes = '[]'; combo.dataset.actions = '0'
        combo.addEventListener('change', event => {
            if (!(event instanceof CustomEvent)) return
            const { value, previousValue } = (event as CustomEvent<ValueChange>).detail
            changes.push({ value, previousValue }); combo.dataset.changes = JSON.stringify(changes)
        })
        for (const name of ['action', 'beforeaction']) combo.addEventListener(name, () => { combo.dataset.actions = String(Number(combo.dataset.actions) + 1) })
        form.append(combo)
        const fixture = document.querySelector<HTMLElement>('#fixture')!
        fixture.style.cssText = 'padding:32px;background:var(--color-surface);color:var(--color-foreground)'
        const heading = document.createElement('h2')
        heading.textContent = 'Countries'; heading.style.cssText = 'font:600 12px/1.4 system-ui;margin:0 0 6px'
        fixture.append(heading, form)
    })
    await expect(page.getByRole('button', { name: 'Remove Austria', exact: true })).toBeVisible()
}

test('combobox reflects changing external errors in native validity and accessible descriptions', async ({ page }) => {
    await mount(page)
    const combo = page.locator('cb-combobox'), input = combo.getByRole('combobox')
    for (const multi of [true, false]) {
        await combo.evaluate((node, multi) => { Object.assign(node, { multi, value: multi ? ['at'] : 'at' } satisfies Partial<Combobox>) }, multi)
        await combo.evaluate(node => node.setAttribute('error-text', 'Choose an option or enter a whole number.'))
        await expect(input).toHaveAttribute('aria-invalid', 'true')
        await expect(input).toHaveAttribute('aria-description', /Choose an option or enter a whole number\./)
        await expect(combo).toHaveJSProperty('validationMessage', 'Choose an option or enter a whole number.')
        await combo.evaluate(node => node.removeAttribute('error-text'))
        await expect(input).not.toHaveAttribute('aria-invalid', 'true')
        await expect(input).not.toHaveAttribute('aria-description', /Choose an option or enter a whole number\./)
        await expect(combo).toHaveJSProperty('validationMessage', '')
    }
})

test('multi combobox selects repeatedly, filters separately, and removes chips without leaking button events', async ({ page }) => {
    await mount(page)
    const combo = page.locator('cb-combobox'), input = combo.getByRole('combobox')
    await expect(combo.locator('cb-icon[name=search]')).toHaveCount(0)
    await input.focus()
    await expect(input).toHaveAttribute('aria-expanded', 'false')
    await input.click()
    await expect(input).toHaveAttribute('aria-expanded', 'true')
    await expect(combo.locator('cb-button[part~=toggle]')).toHaveAttribute('icon', 'up')
    await page.getByRole('button', { name: 'Toggle countries' }).click()
    await expect(input).toHaveAttribute('aria-expanded', 'false')
    await expect(combo.locator('cb-button[part~=toggle]')).toHaveAttribute('icon', 'down')
    await page.getByRole('button', { name: 'Toggle countries' }).click()
    await expect(combo.getByRole('listbox')).toHaveAttribute('aria-multiselectable', 'true')
    await combo.getByRole('option', { name: 'Belgium', exact: true }).click()
    await expect(combo).toHaveJSProperty('value', ['at', 'be'])
    await expect(input).toBeFocused()
    await expect(input).toHaveValue('')
    await expect(input).toHaveAttribute('aria-expanded', 'true')
    await combo.getByRole('option', { name: 'Bulgaria', exact: true }).click()
    await expect(combo).toHaveJSProperty('value', ['at', 'be', 'bg'])
    await expect(combo.getByRole('option', { name: 'Belgium', exact: true })).toHaveAttribute('aria-selected', 'true')
    await combo.getByRole('button', { name: 'Remove Belgium', exact: true }).click()
    await expect(combo).toHaveJSProperty('value', ['at', 'bg'])
    await expect(input).toHaveAttribute('aria-expanded', 'true')
    await input.fill('Czech')
    await expect(combo).toHaveJSProperty('value', ['at', 'bg'])
    await expect(combo.getByRole('option')).toHaveCount(1)
    await input.press('ArrowDown')
    await expect(combo.getByRole('option', { name: 'Czech Republic' })).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(combo).toHaveJSProperty('value', ['at', 'bg', 'cz'])
    await expect(input).toHaveValue('')
    await expect(combo.getByRole('option')).toHaveCount(7)
    await expect(combo.getByRole('option', { name: 'Belarus' })).toBeDisabled()
    await expect(combo).toHaveAttribute('data-changes', JSON.stringify([
        { value: ['at', 'be'], previousValue: ['at'] },
        { value: ['at', 'be', 'bg'], previousValue: ['at', 'be'] },
        { value: ['at', 'bg'], previousValue: ['at', 'be', 'bg'] },
        { value: ['at', 'bg', 'cz'], previousValue: ['at', 'bg'] },
    ] satisfies ValueChange[]))
    await expect(combo).toHaveAttribute('data-actions', '0')
    await input.press('Backspace')
    await expect(combo).toHaveJSProperty('value', ['at', 'bg'])
    await input.press('Escape')
    await expect(input).toHaveAttribute('aria-expanded', 'false')
    await input.fill('Value,')
    await combo.getByRole('option', { name: 'Value, with comma' }).click()
    await expect(combo).toHaveJSProperty('value', ['at', 'bg', 'comma,value'])
    await page.locator('h1').click()
    await expect(input).toHaveAttribute('aria-expanded', 'false')
})

