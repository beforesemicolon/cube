test('multi form values, required validation, reset, restoration, readonly, disabled and vetoes use selected values only', async ({ page }) => {
    await mount(page)
    const combo = page.locator('cb-combobox'), input = combo.getByRole('combobox')
    const formValues = (): Promise<FormDataEntryValue[]> => page.locator('form').evaluate(form => {
        if (!(form instanceof HTMLFormElement)) throw new Error('Missing fixture form')
        return new FormData(form).getAll('country')
    })
    expect(await formValues()).toEqual(['at'])
    await combo.evaluate(node => { (node as Combobox).value = ['be', 'bg'] })
    await expect(combo.locator('[part~=selection]')).toHaveCount(2)
    expect(await formValues()).toEqual(['be', 'bg'])
    await expect(combo).toHaveAttribute('data-changes', '[]')
    await page.locator('form').evaluate(form => { if (form instanceof HTMLFormElement) form.reset() })
    await expect(combo).toHaveJSProperty('value', ['at'])
    await combo.evaluate(node => {
        const restored = new FormData(); restored.append('country', 'cz'); restored.append('country', 'bg')
        ;(node as Combobox).formStateRestoreCallback(restored, 'restore')
    })
    await expect(combo).toHaveJSProperty('value', ['cz', 'bg'])
    await combo.evaluate(node => { Object.assign(node, { required: true, value: [] } satisfies Partial<Combobox>) })
    await input.fill('Czech')
    expect(await combo.evaluate(node => (node as Combobox).checkValidity())).toBe(false)
    expect(await formValues()).toEqual([])
    await combo.getByRole('option', { name: 'Czech Republic' }).click()
    expect(await combo.evaluate(node => (node as Combobox).checkValidity())).toBe(true)
    await combo.evaluate(node => { node.addEventListener('beforechange', event => event.preventDefault(), { once: true }) })
    await combo.getByRole('button', { name: 'Remove Czech Republic' }).click()
    await expect(combo).toHaveJSProperty('value', ['cz'])
    await combo.evaluate(node => { (node as Combobox).readOnly = true })
    await expect(input).toHaveAttribute('readonly')
    await expect(combo.getByRole('button', { name: 'Remove Czech Republic' })).toBeDisabled()
    expect(await combo.evaluate(node => (node as Combobox).removeValue('cz'))).toBe(false)
    await combo.evaluate(node => { Object.assign(node, { readOnly: false, disabled: true } satisfies Partial<Combobox>) })
    await expect(input).toBeDisabled()
    await expect(combo.getByRole('button', { name: 'Remove Czech Republic' })).toBeDisabled()
    expect(await formValues()).toEqual([])
    await combo.evaluate(node => { (node as Combobox).disabled = false })
    await combo.getByRole('button', { name: 'Remove Czech Republic' }).click()
    expect(await combo.evaluate(node => (node as Combobox).checkValidity())).toBe(false)
})

