test('PIN masks other cells while focused, honors cancellation and remains accessible', async ({ page }) => {
    const host = page.locator('cb-verification-code'), input = host.locator('input')
    await host.evaluate(node => { Object.assign(node, { pin: true, value: '012345' } satisfies Partial<VerificationCode>) })
    await expect(input).toHaveAttribute('type', 'password')
    await expect(host.locator('[part=cell]')).toHaveText(['•','•','•','•','•','•'])
    await input.focus()
    await expect(input).toHaveAttribute('type', 'password')
    await expect(host.locator('[part=cell]')).toHaveText(['•','•','•','•','•','5'])
    await host.evaluate(node => node.addEventListener('beforechange', event => event.preventDefault(), { once: true }))
    await input.fill('654321')
    await expect(input).toHaveValue('012345')
    await input.press('Tab')
    await expect(host.locator('[part=cell]')).toHaveText(['•','•','•','•','•','•'])
    expect((await new AxeBuilder({ page }).include('cb-verification-code').analyze()).violations).toEqual([])
    await page.setViewportSize({ width: 320, height: 600 })
    expect(await host.evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true)
    await page.screenshot({ path: '/tmp/cube-verification-code-pin.png' })
})

test('PIN reveals only the current entered or selected cell and masks each previous cell', async ({ page }) => {
    const host = page.locator('cb-verification-code'), input = host.locator('input'), cells = host.locator('[part=cell]')
    await host.evaluate(node => { (node as VerificationCode).pin = true })
    await input.focus()
    for (const [index, digit] of [...'012345'].entries()) {
        await input.press(digit)
        await expect(cells).toHaveText(Array.from({ length: 6 }, (_, cell) => cell < index ? '•' : cell === index ? digit : ''))
        await expect(cells.nth(index)).toHaveAttribute('data-active', 'true')
    }
    await input.click({ position: { x: 95, y: 18 } })
    await expect(cells).toHaveText(['•','•','2','•','•','•'])
    await input.press('9')
    await expect(input).toHaveValue('019345')
    await expect(cells).toHaveText(['•','•','9','•','•','•'])
    await input.press('ArrowRight')
    await expect(cells).toHaveText(['•','•','•','•','4','•'])
    await input.press('Backspace')
    await expect(input).toHaveValue('01945')
    await expect(cells).toHaveText(['•','•','•','4','•',''])
    await input.press('Tab')
    await expect(cells).toHaveText(['•','•','•','•','•',''])
    await input.focus()
    await expect(cells).toHaveText(['•','•','•','4','•',''])
    await host.screenshot({ path: '/tmp/cube-verification-code-pin-current.png' })
    expect(await page.locator('form').evaluate(node => new FormData(node as HTMLFormElement).get('otp_code'))).toBe('01945')
    await input.press('ControlOrMeta+A')
    await input.evaluate(node => {
        const clipboardData = new DataTransfer()
        clipboardData.setData('text/plain', '987654')
        node.dispatchEvent(new ClipboardEvent('paste', { clipboardData, bubbles: true, cancelable: true }))
    })
    await expect(cells).toHaveText(['•','•','•','•','•','4'])
    await input.press('Tab')
    await expect(cells).toHaveText(['•','•','•','•','•','•'])
})
