import { expect } from '@playwright/test'
import type { SegmentedControl } from './index.js'
import { componentContract } from '../../../tests/component-contract.js'

componentContract('cb-segmented-control', 'navigation--segmented-control', async ({ page, host }) => {
    await page.emulateMedia({ reducedMotion: 'reduce' })
    const choices = host.getByRole('radio')
    const first = choices.first()
    const surface = first.locator('[part="control"]')
    for (const appearance of ['light', 'dark']) {
        await page.locator('cb-theme-provider').evaluate((node, value) => node.setAttribute('appearance', value), appearance)
        await expect(surface).toHaveCSS('padding-inline-start', '8px')
        await expect(surface).toHaveCSS('padding-inline-end', '8px')
        await expect(surface).toHaveCSS('column-gap', '4px')
        await expect(first).toHaveCSS('min-height', '28px')
        await expect(first).toHaveCSS('border-radius', '4px')
        await expect(first.locator('cb-icon')).toHaveCSS('width', '14px')
        const track = host.locator('[part="group"]'), idle = choices.nth(1), disabled = choices.nth(2)
        await page.mouse.move(0, 0)
        const idleBackground = await idle.evaluate(node => getComputedStyle(node).backgroundColor)
        expect(idleBackground).not.toBe(await track.evaluate(node => getComputedStyle(node).backgroundColor))
        expect(idleBackground).not.toBe('rgba(0, 0, 0, 0)')
        await host.screenshot({ path: `/tmp/cube-segmented-idle-${appearance}.png` })
        await expect(idle).toHaveCSS('cursor', 'pointer')
        await idle.hover()
        const hoverBackground = await host.evaluate(node => getComputedStyle(node).getPropertyValue('--color-active').trim())
        await expect.poll(() => idle.evaluate(node => getComputedStyle(node).backgroundColor)).not.toBe(idleBackground)
        expect(hoverBackground).not.toBe('')
        const hovered = await idle.evaluate(node => getComputedStyle(node).backgroundColor)
        await host.screenshot({ path: `/tmp/cube-segmented-hover-${appearance}.png` })
        await page.mouse.down()
        await expect.poll(() => idle.evaluate(node => getComputedStyle(node).backgroundColor)).not.toBe(hovered)
        await page.mouse.up()
        await expect(idle).toHaveAttribute('aria-checked', 'true')
        await first.click()
        await expect(first).toHaveAttribute('aria-checked', 'true')
        const disabledBackground = await disabled.evaluate(node => getComputedStyle(node).backgroundColor)
        await disabled.hover()
        await expect(disabled).toHaveCSS('cursor', 'not-allowed')
        await expect(disabled).toHaveCSS('background-color', disabledBackground)
        const widths = await choices.evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().width))
        expect(Math.max(...widths) - Math.min(...widths)).toBeLessThan(1)
        const spacing = await first.evaluate(node => {
            const control = node.shadowRoot?.querySelector('[part="control"]')
            const icon = node.shadowRoot?.querySelector('cb-icon')
            const label = node.shadowRoot?.querySelector('[part="button-label"]')
            if (!control || !icon || !label) throw new Error('Missing segmented control anatomy')
            const outer = control.getBoundingClientRect(), leading = icon.getBoundingClientRect(), text = label.getBoundingClientRect()
            return { before: leading.left - outer.left, between: text.left - leading.right, after: outer.right - text.right }
        })
        expect(spacing.before).toBeGreaterThanOrEqual(8)
        expect(spacing.between).toBeCloseTo(4, 1)
        expect(spacing.after).toBeGreaterThanOrEqual(8)
    }
    await host.evaluate(node => { Object.assign(node, { stacked: true } satisfies Partial<SegmentedControl>) })
    const rows = await choices.evaluateAll(nodes => nodes.map(node => {
        const box = node.getBoundingClientRect()
        return { left: box.left, right: box.right, top: box.top, bottom: box.bottom }
    }))
    expect(rows[1]!.top).toBeGreaterThanOrEqual(rows[0]!.bottom)
    expect(rows[0]!.left).toBeCloseTo(rows[1]!.left, 1)
    expect(rows[0]!.right).toBeCloseTo(rows[1]!.right, 1)
    await host.evaluate(node => {
        Object.assign(node, { stacked: false } satisfies Partial<SegmentedControl>)
        node.style.setProperty('--component-segmented-control-item-padding-inline', '14px')
        node.style.setProperty('--component-segmented-control-item-min-height', '32px')
    })
    await expect(surface).toHaveCSS('padding-inline-start', '14px')
    await expect(first).toHaveCSS('min-height', '32px')
    await host.evaluate(node => {
        node.style.removeProperty('--component-segmented-control-item-padding-inline')
        node.style.removeProperty('--component-segmented-control-item-min-height')
    })
    await page.locator('cb-theme-provider').evaluate(node => node.setAttribute('appearance', 'light'))
    await host.evaluate(node => { Object.assign(node, {"items":[{"id":"release","label":"Release choice"}],"value":"release"} satisfies Partial<SegmentedControl>) })
    await expect(host.getByRole('radio', { name: 'Release choice', exact: true })).toHaveAttribute('aria-checked', 'true')
    await host.evaluate(node => { Object.assign(node, { iconOnly: true, items: [
        { id: 'left', label: 'Align left', icon: 'alignLeft' }, { id: 'right', label: 'Align right', icon: 'alignRight' },
    ], value: 'left' } satisfies Partial<SegmentedControl>) })
    const right = host.getByRole('radio', { name: 'Align right', exact: true })
    await expect(right).toHaveAttribute('data-icon-only', '')
    await expect(right.locator('[part="control"]')).toHaveCSS('padding-inline-start', '4px')
    await expect(right).toHaveCSS('width', '24px')
    await host.evaluate(node => { Object.assign(node, { size: 'xs' } satisfies Partial<SegmentedControl>) })
    await expect(right).toHaveAttribute('size', 'xs')
    await expect(right).toHaveAttribute('data-size', 'xs')
    await expect(right).toHaveCSS('width', '18px')
    await expect(right).toHaveCSS('min-height', '20px')
    await expect(right.locator('cb-icon')).toHaveCSS('width', '12px')
    await expect(right.locator('[part="control"]')).toHaveCSS('padding-inline-start', '2px')
    await host.evaluate(node => { Object.assign(node, { size: 'sm' } satisfies Partial<SegmentedControl>) })
    await expect(right.locator('[part~="button-label"]')).toHaveAttribute('part', /sr-only/)
    await right.click()
    await expect(right).toHaveAttribute('aria-checked', 'true')
    await right.press('ArrowLeft')
    const left = host.getByRole('radio', { name: 'Align left', exact: true })
    await expect(left).toBeFocused()
    await left.press('Space')
    await expect(left).toHaveAttribute('aria-checked', 'true')
    await host.evaluate(node => { Object.assign(node, { iconOnly: false } satisfies Partial<SegmentedControl>) })
    await expect(right.locator('[part~="button-label"]')).not.toHaveAttribute('part', /sr-only/)
    await host.evaluate(node => { Object.assign(node, { iconOnlyAt: 'md' } satisfies Partial<SegmentedControl>) })
    await expect(host).toHaveAttribute('data-icon-only-at', 'md')
    await page.setViewportSize({ width: 600, height: 720 })
    await expect(right.locator('[part~="button-label"]')).toHaveCSS('position', 'absolute')
    await expect(right).toHaveCSS('min-width', '24px')
    await expect(right.locator('[part="control"]')).toHaveCSS('padding-inline-start', '4px')
    await expect(right).toHaveCSS('width', '24px')
    await page.setViewportSize({ width: 1024, height: 720 })
    await expect(right.locator('[part~="button-label"]')).not.toHaveCSS('position', 'absolute')
    await host.evaluate(node => {
        Object.assign(node, { iconOnlyAt: '', closeLabel: 'Close {item}', items: [
            { id: 'canvas', label: 'Canvas' },
            { id: 'page', label: 'Page' },
            { id: 'one', label: 'HeroCard', closable: true },
            { id: 'two', label: 'SiteHeader', closable: true },
            { id: 'locked', label: 'LockedCard', closable: true, disabled: true },
        ], value: 'two' } satisfies Partial<SegmentedControl>)
        node.dataset.changes = '0'
        node.addEventListener('change', () => { node.dataset.changes = String(Number(node.dataset.changes) + 1) })
    })
    await expect(host.getByRole('button', { name: 'Close Canvas', exact: true })).toHaveCount(0)
    await expect(host.getByRole('button', { name: 'Close LockedCard', exact: true })).toBeDisabled()
    const header = host.getByRole('radio', { name: 'SiteHeader', exact: true })
    await expect(header).toHaveAttribute('aria-checked', 'true')
    await expect(host.locator('[part=segment][data-selected=true]')).not.toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
    await host.getByRole('button', { name: 'Close HeroCard', exact: true }).click()
    await expect(host.getByRole('radio', { name: 'HeroCard', exact: true })).toHaveCount(0)
    await expect(header).toHaveAttribute('aria-checked', 'true')
    await host.evaluate(node => node.addEventListener('beforeclose', event => event.preventDefault(), { once: true }))
    const closeHeader = host.getByRole('button', { name: 'Close SiteHeader', exact: true })
    await closeHeader.click()
    await expect(header).toHaveAttribute('aria-checked', 'true')
    await closeHeader.press('Enter')
    await expect(header).toHaveCount(0)
    await expect(host.getByRole('radio', { name: 'Page', exact: true })).toHaveAttribute('aria-checked', 'true')
    await expect(host).toHaveAttribute('data-changes', '0')
    await host.evaluate(node => { Object.assign(node, { multiple: true, values: ['one', 'two'], items: [
        { id: 'one', label: 'First', closable: true }, { id: 'two', label: 'Second', closable: true },
    ] } satisfies Partial<SegmentedControl>) })
    await host.getByRole('button', { name: 'Close First', exact: true }).click()
    await expect(host).toHaveJSProperty('values', ['two'])
    await host.getByRole('button', { name: 'Close Second', exact: true }).click()
    await expect(host.getByRole('checkbox')).toHaveCount(0)
    await expect(host).toHaveJSProperty('values', [])
})
